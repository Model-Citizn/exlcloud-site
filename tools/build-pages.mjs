#!/usr/bin/env node
/*
 * EXL Cloud — static route builder
 * ---------------------------------
 * The site is a single React app living in /index.html (the SOURCE OF TRUTH).
 * GitHub Pages needs a real file at every URL, so each route (/about, /gen2,
 * /articles/<slug> …) is a copy of index.html with its own <title>, meta
 * description, canonical URL, Open Graph tags, JSON-LD and pre-rendered
 * crawler text. This script generates all of those copies plus sitemap.xml.
 *
 * NEVER edit about/index.html, articles/<slug>/index.html etc. by hand —
 * edit index.html / articles-data.jsx and re-run:
 *
 *     node tools/build-pages.mjs          # regenerate everything
 *     node tools/build-pages.mjs --check  # CI: fail if anything is out of date
 *
 * Bump SITE_UPDATED when you make a site-wide content change (drives sitemap lastmod).
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const SITE_UPDATED = "2026-11-14";
const ORIGIN = "https://exlcloud.io";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

/* Claims that must never reappear anywhere in the live source (stale counts / old prices). */
const STALE_PATTERNS = [
  { re: /\b(1\d|2[1-9]) (purpose-built )?(Claude )?(AI[- ]powered|AI) skills/gi, why: "skill count must read \"20+\" (see Gen 2 skills list for the actual list)" },
  { re: /\b(1\d) purpose-built skills/gi, why: "skill count must read \"20+\"" },
  { re: /\$(50|125) AUD/g, why: "old pricing — plans are $70 / $170 AUD per month" },
  { re: /Boot Camp/g, why: "Boot Camp is unavailable on Apple silicon — say Parallels Desktop" },
];

const PAGES = {
  about: { priority: "0.8", freq: "monthly" },
  features: { priority: "0.9", freq: "monthly" },
  articles: { priority: "0.9", freq: "weekly" },
  gen2: { priority: "0.8", freq: "monthly" },
  pricing: { priority: "0.9", freq: "monthly" },
  support: { priority: "0.7", freq: "monthly" },
  future: { priority: "0.8", freq: "monthly" },
  contact: { priority: "0.7", freq: "monthly" },
  privacy: { priority: "0.3", freq: "yearly" },
  eula: { priority: "0.3", freq: "yearly" },
};

const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const escAttr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escText = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const jsonLd = (o) => JSON.stringify(o).replace(/<\//g, "<\\/");
const plain = (html) => String(html).replace(/<[^>]+>/g, " ").replace(/&amp;/g, "&").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();
const clip = (s, n = 158) => {
  s = plain(s);
  if (s.length <= n) return s;
  const cut = s.slice(0, n - 1);
  return cut.slice(0, cut.lastIndexOf(" ")).replace(/[,;:.\s—-]+$/, "") + "…";
};

/* ── load sources ─────────────────────────────────────────── */
const template = read("index.html");
const ctx = { window: {} };
vm.runInNewContext(read("articles-data.jsx").replace("const ARTICLES", "var ARTICLES"), ctx);
const ARTICLES = ctx.ARTICLES;
const metaSrc = template.match(/const PAGE_META = (\{[\s\S]*?\n\});/);
if (!metaSrc) throw new Error("PAGE_META not found in index.html");
const PAGE_META = vm.runInNewContext("(" + metaSrc[1] + ")");

/* ── validate sources ─────────────────────────────────────── */
const problems = [];
const slugs = new Set();
for (const a of ARTICLES) {
  for (const k of ["title", "slug", "author", "date", "excerpt", "content"]) if (!a[k]) problems.push(`article ${a.slug || a.title}: missing ${k}`);
  if (slugs.has(a.slug)) problems.push(`duplicate article slug ${a.slug}`);
  slugs.add(a.slug);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(a.date)) problems.push(`article ${a.slug}: bad date ${a.date}`);
}
for (const p of Object.keys(PAGES)) if (!PAGE_META[p]) problems.push(`PAGE_META missing "${p}"`);
const scan = { "index.html": template, "articles-data.jsx": read("articles-data.jsx") };
for (const [file, txt] of Object.entries(scan))
  for (const { re, why } of STALE_PATTERNS)
    for (const m of txt.matchAll(re)) problems.push(`${file}: stale claim "${m[0]}" — ${why}`);
if (problems.length) {
  console.error("✗ Source validation failed:\n  " + problems.join("\n  "));
  process.exit(1);
}

/* ── page generation ──────────────────────────────────────── */
const AEO_RE = /(<div id="aeo-content"[^>]*>)[\s\S]*?(\n  <\/div>)/;
const homeAeo = template.match(AEO_RE);
if (!homeAeo) throw new Error("aeo-content block not found");
const homeAeoBody = template.match(/<div id="aeo-content"[^>]*>([\s\S]*?)\n  <\/div>/)[1];
const companyPara = homeAeoBody.match(/\n    <p>EXL Cloud Pty Ltd,[^\n]*<\/p>/)?.[0] || "";

function ogBlock({ title, desc, url, type = "website", image = `${ORIGIN}/images/logo-exlcloud500.png` }) {
  return [
    `  <!-- og:start (generated by tools/build-pages.mjs) -->`,
    `  <meta property="og:site_name" content="EXL Cloud" />`,
    `  <meta property="og:type" content="${type}" />`,
    `  <meta property="og:title" content="${escAttr(title)}" />`,
    `  <meta property="og:description" content="${escAttr(desc)}" />`,
    `  <meta property="og:url" content="${url}" />`,
    `  <meta property="og:image" content="${image}" />`,
    `  <meta property="og:locale" content="en_AU" />`,
    `  <meta name="twitter:card" content="summary_large_image" />`,
    `  <meta name="twitter:site" content="@exl_cloud" />`,
    `  <!-- og:end -->`,
  ].join("\n");
}

function render({ base, title, desc, canonical, extraHead = "", og, aeo }) {
  let h = template;
  h = h.replace(/\n  <!-- og:start[\s\S]*?<!-- og:end -->/, "");
  h = h.replace(/\n  <script type="application\/ld\+json" data-page>[^\n]*<\/script>/, "");
  h = h.replace(/\n  <base href="\/" \/>/, "");
  if (base) h = h.replace('  <meta charset="UTF-8" />\n', '  <meta charset="UTF-8" />\n  <base href="/" />\n');
  /* function replacers throughout: descriptions contain "$70" which a string replacer would treat as a group ref */
  h = h.replace(/<meta name="description" content="[^"]*" \/>/, () => `<meta name="description" content="${escAttr(desc)}" />`);
  h = h.replace(/<title>[^<]*<\/title>/, () => `<title>${escText(title)}</title>`);
  h = h.replace(/<link rel="canonical" href="[^"]*" \/>/, () => `<link rel="canonical" href="${canonical}" />${extraHead}\n${ogBlock(og)}`);
  h = h.replace(AEO_RE, (_, open, close) => `${open}${aeo}${close}`);
  return h;
}

const out = new Map();
const [homeTitle, homeDesc] = PAGE_META.home;
out.set("index.html", render({ base: false, title: homeTitle, desc: homeDesc, canonical: `${ORIGIN}/`, og: { title: homeTitle, desc: homeDesc, url: `${ORIGIN}/` }, aeo: homeAeoBody }));

for (const p of Object.keys(PAGES)) {
  const [title, desc] = PAGE_META[p];
  const url = `${ORIGIN}/${p}`;
  let aeo = `\n    <h1>${escText(title)}</h1>\n    <p>${escText(desc)}</p>`;
  if (p === "articles")
    aeo += `\n    <ul>\n${ARTICLES.map((a) => `      <li><a href="/articles/${a.slug}">${escText(a.title)}</a> — ${escText(clip(a.excerpt, 200))}</li>`).join("\n")}\n    </ul>`;
  aeo += homeAeoBody.replace(/\n    <h1>[^\n]*<\/h1>/, "");
  out.set(`${p}/index.html`, render({ base: true, title, desc, canonical: url, og: { title, desc, url }, aeo }));
}

for (const a of ARTICLES) {
  const url = `${ORIGIN}/articles/${a.slug}`;
  const title = `${a.title} | EXL Cloud Articles`;
  const desc = clip(a.excerpt);
  const imgFile = `images/articles/${a.slug}.png`;
  const image = fs.existsSync(path.join(ROOT, imgFile)) ? `${ORIGIN}/${imgFile}` : undefined;
  const authors = [{ "@type": "Person", name: a.author }];
  if (a.coauthor) authors.push({ "@type": "Person", name: a.coauthor });
  const ld = {
    "@context": "https://schema.org", "@type": "BlogPosting",
    headline: a.title, description: desc,
    datePublished: a.date, dateModified: a.updated || a.date,
    author: authors.length === 1 ? authors[0] : authors,
    keywords: (a.tags || []).join(", "),
    ...(image ? { image } : {}),
    mainEntityOfPage: url,
    publisher: { "@type": "Organization", name: "EXL Cloud Pty Ltd", url: ORIGIN, logo: { "@type": "ImageObject", url: `${ORIGIN}/images/logo-exlcloud500.png` } },
  };
  const byline = `${a.author}${a.coauthor ? " &amp; " + escText(a.coauthor) : ""}`;
  const aeo = `\n    <article>\n      <h1>${escText(a.title)}</h1>\n      <p>By ${byline} · Published ${a.date}</p>\n      <p>${escText(plain(a.excerpt))}</p>\n${a.content}\n    </article>${companyPara}`;
  out.set(`articles/${a.slug}/index.html`, render({
    base: true, title, desc, canonical: url,
    extraHead: `\n  <script type="application/ld+json" data-page>${jsonLd(ld)}</script>`,
    og: { title: a.title, desc, url, type: "article", image }, aeo,
  }));
}

/* ── sitemap ──────────────────────────────────────────────── */
const urlTag = (loc, lastmod, freq, pri) => `  <url><loc>${loc}</loc><lastmod>${lastmod}</lastmod><changefreq>${freq}</changefreq><priority>${pri}</priority></url>`;
const newest = ARTICLES.map((a) => a.updated || a.date).sort().pop();
const sm = [
  `<?xml version="1.0" encoding="UTF-8"?>`,
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`,
  urlTag(`${ORIGIN}/`, SITE_UPDATED, "weekly", "1.0"),
  ...Object.entries(PAGES).map(([p, m]) => urlTag(`${ORIGIN}/${p}`, p === "articles" && newest > SITE_UPDATED ? newest : SITE_UPDATED, m.freq, m.priority)),
  ...[...ARTICLES].sort((x, y) => (y.date > x.date ? 1 : -1)).map((a) => urlTag(`${ORIGIN}/articles/${a.slug}`, a.updated || a.date, "yearly", a.date >= "2026-01-01" ? "0.8" : "0.7")),
  `</urlset>`,
  ``,
].join("\n");
out.set("sitemap.xml", sm);

/* ── write / check ────────────────────────────────────────── */
const stale = [];
for (const [rel, content] of out) {
  const abs = path.join(ROOT, rel);
  const cur = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (cur === content) continue;
  stale.push(rel);
  if (!CHECK) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, content); }
}
/* orphaned article folders (article removed from articles-data.jsx) */
const orphans = fs.readdirSync(path.join(ROOT, "articles"), { withFileTypes: true })
  .filter((d) => d.isDirectory() && !slugs.has(d.name)).map((d) => `articles/${d.name}/`);

if (CHECK) {
  if (stale.length || orphans.length) {
    console.error(`✗ ${stale.length} generated file(s) out of date${orphans.length ? `, ${orphans.length} orphaned` : ""}. Run: node tools/build-pages.mjs`);
    for (const f of [...stale, ...orphans]) console.error("  - " + f);
    process.exit(1);
  }
  console.log(`✓ ${out.size} generated files up to date (${ARTICLES.length} articles, ${Object.keys(PAGES).length + 1} pages).`);
} else {
  console.log(`✓ Built ${out.size} files (${stale.length} changed). ${ARTICLES.length} articles, ${Object.keys(PAGES).length + 1} pages.`);
  if (orphans.length) console.warn("⚠ Orphaned article folders (not in articles-data.jsx):\n  " + orphans.join("\n  "));
}
